/**
 * @file SpecsynLibChained.hpp
 * @author Mark Krumholz
 * @brief A spectral synthesizer that chains together several SpecsynLib libraries
 * @date 2026-07-21
 */

#ifndef SPECSYNLIBCHAINED_HPP
#define SPECSYNLIBCHAINED_HPP

#include "../io/SimControls.hpp"
#include "Specsyn.hpp"
#include <cstddef>
#include <limits>
#include <memory>
#include <string>
#include <vector>

namespace specsyn
{

    /**
     * @class SpecsynLibChained
     * @brief A Specsyn specialization that chains together several SpecsynLib libraries
     * @details
     * Some parts of stellar parameter space are best covered by
     * different spectral libraries -- for example, an OB-star library
     * like TLUSTY for hot, massive stars, and a library like BOSZ for
     * cooler, lower-mass stars. This class lets several such libraries
     * be combined into a single Specsyn: each one is tried in turn, in
     * priority order, and the first one able to produce a spectrum for
     * a given star is used.
     *
     * Chained libraries need not share a single native wavelength
     * grid, so the constructor builds a common grid spanning all of
     * them (see makeCommonWlGrid) and resamples every library onto it
     * (see SpecsynLib::resample) before storing them.
     */
    class SpecsynLibChained : public Specsyn
    {
    public:

        /**
         * @brief Construct a SpecsynLibChained from a list of spectral libraries on disk
         * @param spectraName The names of the spectral models to chain
         *   together, in priority order: if a star's parameters fall
         *   within more than one of these libraries' grids, the
         *   spectrum is generated by whichever one appears earliest in
         *   this list
         * @param fehMin Minimum [Fe/H] value
         * @param fehMax Maximum [Fe/H] value
         * @param afe Value of [alpha/Fe]
         * @param cfe Value of [C/Fe]
         * @param microTurb Microturbulent velocity, in km/s, one entry
         *   per entry of spectraName (different libraries -- e.g. an
         *   OB-star library versus one covering cooler, lower-mass
         *   stars -- commonly assume different microturbulent
         *   velocities). An empty vector (the default) uses each
         *   library's own micro_default value from the registry
         *   instead (see SpecsynLib's constructor), rather than
         *   forcing every library in the chain to share one value.
         * @param r Spectral resolution
         * @param registryName Name of the spectral library registry file
         * @param wlMin Minimum wavelength of the output grid, in
         *   Angstrom; if 0 (the default), used together with wlMax
         *   and nWl below (see @details) as a flag to fall back on
         *   each library's own native wavelength coverage
         * @param wlMax Maximum wavelength of the output grid, in
         *   Angstrom; see wlMin
         * @param nWl Number of points in the output grid; if 0 (the
         *   default), used as a flag to fall back on each library's
         *   own native wavelength grid -- see @details
         * @param tClamp Whether to clamp a star's log(Teff) to the
         *   combined range spanned by every chained library before
         *   calling spec() on it; defaults to true. See @details.
         * @throws std::runtime_error if spectraName is empty, or if
         *   microTurb is non-empty and its size does not match
         *   spectraName's
         * @details
         * Constructs one library per entry of spectraName, in order --
         * a SpecsynLibWR for an entry whose registry entry has
         * WR_grid = true, a SpecsynLibNoWind for every other entry --
         * pairing each one with the corresponding entry of microTurb
         * (or that library's own registry default, if microTurb is
         * empty; ignored entirely for a SpecsynLibWR entry, which has
         * no microTurb axis) and otherwise using the remaining
         * arguments -- including wlMin, wlMax, and nWl -- unchanged
         * for each one. Every library but the last
         * is constructed with OOBPolicy::coerce, so a star outside its
         * grid (or in one of its gaps) is still handled by that same
         * library if it has at least one valid neighboring grid point,
         * and falls through to the next library in the chain only if
         * it truly has none; the last library is constructed with
         * OOBPolicy::raise, so a star nothing in the chain can cover at
         * all -- not even by coercion -- still produces an error rather
         * than silently vanishing.
         * Each is upcast to (and stored as) the SpecsynLib<Policy> it
         * was constructed as a specialization of, since every function
         * this class actually needs -- resample(), wl(), spec() --
         * lives on that parent.
         *
         * Once every library has been loaded on its own native
         * wavelength grid, makeCommonWlGrid is used to build a single
         * grid spanning all of them, and each library is resampled
         * (see SpecsynLib::resample) onto that common grid, so that
         * every chained library's spec() output shares the same
         * length and wavelength values -- and so that wl() correctly
         * describes every one of them, not just the first.
         *
         * If tClamp is true, also scans every chained SpecsynLibNoWind
         * or SpecsynLibWR library's own log(Teff) grid (via their
         * logTeff() accessors) for the global minimum and maximum,
         * storing them in logTeffMin_/logTeffMax_ for spec() to clamp
         * against (see spec()'s own comment); if false, both are set
         * to quiet_NaN() instead, so spec() applies no clamp at all.
         * This exists to work around a real quirk in some evolutionary
         * tracks (e.g. MIST), whose effective temperatures for
         * stripped, strong-wind stars can run far hotter than any
         * spectral library actually covers -- and hotter than any
         * known real star, since the whole premise of an effective
         * temperature derived this way breaks down once the photosphere
         * itself forms well above the stellar surface. Clamping to
         * what the chained libraries actually cover is a deliberate
         * choice to use the hottest (or coolest) library grid point as
         * a stand-in in that regime, rather than raising or silently
         * dropping the star.
         *
         * Likewise scans every chained SpecsynLibNoWind library's own
         * log(g) grid (via logg()) for loggMin_/loggMax_ -- again both
         * quiet_NaN() if tClamp is false. SpecsynLibWR contributes
         * nothing here, since Wolf-Rayet atmospheres aren't
         * parameterized by logg at all (see spec()'s own comment for
         * how this clamp is actually applied, which is necessarily
         * more involved than the logTeff one above). This addresses a
         * distinct, genuine gap in every currently available spectral
         * library -- not a track quirk this time, but real atmosphere
         * grids simply not extending to the very low log(g) reached by
         * red supergiants, since that regime is hard for atmosphere
         * codes to model at all.
         * @param controls Simulation controls; forwarded unchanged to
         *   Specsyn's own constructor -- see its comment. Has no
         *   default of its own (unlike every parameter above): a
         *   reference bound to a temporary default-constructed
         *   SimControls would dangle the moment this constructor
         *   returned, since this class stores it live rather than
         *   copying out of it.
         */
        SpecsynLibChained(
            const std::vector<std::string>& spectraName,
            double fehMin,
            double fehMax,
            double afe,
            double cfe,
            const std::vector<double>& microTurb,
            double r,
            const std::string& registryName,
            double wlMin,
            double wlMax,
            std::size_t nWl,
            bool tClamp,
            const io::SimControls& controls);

        /**
         * @brief Compute a star's spectrum by trying each chained library in turn
         * @param props Stellar properties, as produced by evaluating
         *   the Interpolator1D returned by Tracks2D::getIsochrone at
         *   this star's mass
         * @param feh [Fe/H] value of the star; needed because it is
         *   not carried by props itself
         * @return The star's spectrum, evaluated on the wavelength
         *   grid returned by wl(), in units of erg/s/Angstrom, as
         *   produced by the first chained library able to generate one
         * @throws std::runtime_error if the star falls outside every
         *   chained library's grid
         * @details
         * If the constructor's tClamp argument was true, first clamps
         * a copy of props' log(Teff) entry to [logTeffMin_,
         * logTeffMax_] -- the combined range spanned by every chained
         * SpecsynLibNoWind/SpecsynLibWR library's own grid -- before
         * doing anything else with it (logTeffMin_/logTeffMax_ are
         * quiet_NaN() otherwise, so the comparison is simply skipped).
         * A copy is needed here since props itself is a const
         * reference, but the cost is negligible next to the
         * interpolation work spec() goes on to do.
         *
         * Next, if loggMin_/loggMax_ are not quiet_NaN() (see the
         * constructor), classifies the star via
         * SpecsynLibWR::getWRType: a Wolf-Rayet star (anything but
         * WRType::None) is left alone here, since its analogous
         * clamp (on transformed radius, not logg) is already handled
         * internally by SpecsynLibWR::spec() itself. For any other
         * star, computes log(g) via Specsyn::getSAandLogg and, if it
         * falls outside [loggMin_, loggMax_], rescales the copy's mass
         * entry -- rather than its luminosity or Teff, which would
         * perturb the surface area (and hence the wavelength-dependent
         * shape of the emergent spectrum) getSAandLogg derives from
         * those two alone -- by 10^((loggMin_ - logg) + 1e-10) (below
         * loggMin_) or 10^((loggMax_ - logg) - 1e-10) (above loggMax_).
         * Since log(g) is exactly linear in log10(mass) with unit slope
         * (at fixed radius, i.e. fixed log(L)/log(Teff)), this lands
         * log(g) exactly 1e-10 dex past the relevant bound -- close
         * enough to be physically meaningless, but far enough that
         * floating-point roundoff in the subsequent recomputation can't
         * leave it just outside that bound again.
         *
         * Finally calls spec() on each library in the chain in
         * priority order, stopping at and returning the first
         * non-empty result. The last library in the chain is
         * constructed with OOBPolicy::raise, so if every earlier
         * library returns an empty (out-of-bounds) result, this call
         * throws rather than returning silently.
         */
        [[nodiscard]] auto spec(const StarData& props, double feh) const
        -> std::vector<double> override;

        /**
         * @brief Build a common wavelength grid spanning several libraries' own grids
         * @param wlGrids One wavelength grid per library, each sorted
         *   ascending and non-empty
         * @return A single sorted, deduplicated wavelength grid
         *   spanning the full range covered by wlGrids
         * @throws std::runtime_error if wlGrids, or any grid in it, is empty
         * @details
         * Splits the full wavelength range into windows delineated by
         * every grid's minimum and maximum wavelength -- e.g. grids
         * covering [200, 2000] and [1500, 3000] Angstrom split the
         * range into windows [200, 1500], [1500, 2000], and
         * [2000, 3000]. Within each window, restricts to grids whose
         * own range fully contains it, and adopts whichever of those
         * has the most points there (ties favor the earlier grid in
         * wlGrids); this "fully contains" restriction matters because
         * a grid whose own range happens to end (or start) exactly at
         * one edge of a window still has that one boundary point
         * technically inside it, which could otherwise spuriously tie
         * against (or even beat) another grid that actually spans the
         * window. If no grid fully contains a window, falls back to
         * whichever grid simply has the most points physically
         * present there, so a grid's own trailing edge point is still
         * kept when nothing else reaches anywhere near it; a window
         * with no points from any grid at all (a genuine coverage gap)
         * contributes nothing to the result, rather than inventing
         * samples there. The result is these per-window selections
         * concatenated in order, so it is itself sorted and spans the
         * union of every input grid's range wherever that union has no
         * gaps.
         *
         * This is a general-purpose grid-merging utility, not tied to
         * SpecsynLibChained's own constructor use of it (which passes
         * the wl() of each of its chained libraries), so it takes
         * wavelength grids directly rather than Specsyn/SpecsynLib
         * objects.
         */
        [[nodiscard]] static auto makeCommonWlGrid(
            const std::vector<std::vector<double>>& wlGrids) -> std::vector<double>;

    private:

        /**
         * @brief The chained libraries, in priority order
         * @details
         * Stored as pointers to the polymorphic Specsyn base, rather
         * than as SpecsynLib values directly, because each library's
         * OOBPolicy is a compile-time template parameter -- the
         * coerce-policy libraries earlier in the chain and the
         * raise-policy library at its end are genuinely different
         * types, and only differ in which OOBPolicy they were built
         * with.
         */
        std::vector<std::unique_ptr<Specsyn>> libs_;

        /**
         * @brief The combined log(Teff) range spanned by every chained library
         * @details
         * Both quiet_NaN() if the constructor's tClamp argument was
         * false; otherwise the minimum/maximum, respectively, of every
         * chained SpecsynLibNoWind/SpecsynLibWR library's own logTeff()
         * grid. See the constructor's and spec()'s own comments.
         */
        double logTeffMin_ = std::numeric_limits<double>::quiet_NaN();
        double logTeffMax_ = std::numeric_limits<double>::quiet_NaN(); /**< See logTeffMin_ */

        /**
         * @brief The combined log(g) range spanned by every chained SpecsynLibNoWind library
         * @details
         * Both quiet_NaN() if the constructor's tClamp argument was
         * false; otherwise the minimum/maximum, respectively, of every
         * chained SpecsynLibNoWind library's own logg() grid (WR
         * libraries contribute nothing here -- see the constructor's
         * own comment). See the constructor's and spec()'s own
         * comments.
         */
        double loggMin_ = std::numeric_limits<double>::quiet_NaN();
        double loggMax_ = std::numeric_limits<double>::quiet_NaN(); /**< See loggMin_ */
    };

} // namespace specsyn

#endif // SPECSYNLIBCHAINED_HPP
